#!/usr/bin/env python3
"""verify_ml.py — machine checks for the Messages SMS-model work. No narrative, no scores.

Run from anywhere inside the repo:   python3 scripts/verify_ml.py
Exit code 0 = no FAIL. DO NOT EDIT THIS FILE: the reviewer runs the same file on the pushed commit.
"""
import glob, hashlib, json, os, re, subprocess, sys

ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
os.chdir(ROOT)
FAILS = WARNS = 0


def out(level, msg):
    global FAILS, WARNS
    print(f"{level:<5} {msg}")
    if level == "FAIL":
        FAILS += 1
    if level == "WARN":
        WARNS += 1


def tracked():
    return subprocess.check_output(["git", "ls-files"], text=True).splitlines()


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


FILES = tracked()
print("commit:", subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], text=True).strip())
print("-" * 60)

# 1. The AI release gate may only be opened with an explicit, hash-bound owner approval.
gate_file = "protection-engine/src/main/kotlin/com/messages/protection/AiScorer.kt"
gate_open = False
if os.path.exists(gate_file):
    m = re.search(r"const\s+val\s+AI_LAYER_ENABLED\s*=\s*(true|false)", open(gate_file, encoding="utf-8").read())
    gate_open = bool(m and m.group(1) == "true")
if not gate_open:
    out("PASS", "1  AI_LAYER_ENABLED is false (research-only gate closed)")
else:
    ap = "docs/ml/OWNER_APPROVAL.md"
    model = "protection-engine/src/main/resources/ngram_model.json"
    ok = False
    if os.path.exists(ap) and os.path.exists(model):
        txt = open(ap, encoding="utf-8").read()
        ok = ("APPROVED" in txt) and (sha256(model) in txt)
    out("PASS" if ok else "FAIL", "1  AI_LAYER_ENABLED=true " + ("with OWNER_APPROVAL.md bound to the model hash" if ok else "WITHOUT docs/ml/OWNER_APPROVAL.md containing APPROVED and the model sha256"))

# 2. Shipped model assets must stay inside the 2 MiB budget.
big = []
for p in FILES:
    if p.startswith("protection-engine/src/main/resources/") and p.endswith((".json", ".bin", ".tflite", ".onnx", ".pt")):
        if os.path.getsize(p) > 2 * 1024 * 1024:
            big.append(f"{p} ({os.path.getsize(p)} B)")
out("PASS" if not big else "FAIL", "2  shipped model assets <= 2 MiB" if not big else "2  oversized asset(s): " + ", ".join(big))

# 3. No raw/private message data or archives in git.
bad_pat = re.compile(r"(PRIVATE|sms_raw|raw_messages|_export|acceptance_set)", re.I)
bad_ext = (".xlsx", ".xls", ".db", ".sqlite", ".zip", ".7z", ".rar", ".parquet", ".arrow")
bad = [p for p in FILES if (bad_pat.search(os.path.basename(p)) or p.lower().endswith(bad_ext)) and not p.startswith(("docs/reviews/",))]
bad = [p for p in bad if not p.endswith((".md", ".py", ".kt", ".sh"))]
out("PASS" if not bad else "FAIL", "3  no raw/private/archive/acceptance data tracked" if not bad else "3  tracked private-looking data: " + ", ".join(bad[:6]))

# 4. Dataset manifest: every dataset has provenance, license and a declared use.
mf = "docs/ml/datasets_manifest.json"
FIT_OK = {"cc0-1.0", "cc-by-4.0", "cc-by-sa-4.0", "mit", "apache-2.0", "bsd-3-clause", "odc-by", "pddl", "cc-by-3.0", "public-domain", "owner-created", "godl-india"}
if not os.path.exists(mf):
    out("FAIL", "4  docs/ml/datasets_manifest.json missing (required from Phase 1)")
else:
    try:
        entries = json.load(open(mf, encoding="utf-8"))
        entries = entries["datasets"] if isinstance(entries, dict) else entries
        problems = []
        for e in entries:
            for k in ("name", "source_url", "license", "retrieved_at", "sha256", "use", "languages", "rows", "labels_mapping"):
                if k not in e:
                    problems.append(f"{e.get('name','?')}: missing {k}")
            if e.get("use") not in ("fit", "dev", "diagnostic", "excluded"):
                problems.append(f"{e.get('name','?')}: bad use {e.get('use')}")
            if e.get("use") == "fit" and str(e.get("license", "")).lower() not in FIT_OK:
                problems.append(f"{e.get('name','?')}: license '{e.get('license')}' not allowed for fit")
        out("PASS" if not problems and entries else "FAIL", f"4  dataset manifest valid ({len(entries)} entries)" if not problems and entries else "4  manifest problems: " + "; ".join(problems[:5]) if problems else "4  manifest is empty")
    except Exception as ex:
        out("FAIL", f"4  manifest unreadable: {ex}")

# 5. Unsafe model/data loading in training and evaluation code.
unsafe = []
for p in FILES:
    if p.endswith(".py") and not p.endswith("scripts/verify_ml.py") and (p.startswith("protection-engine/") or p.startswith("scripts/") or p.startswith("ml/")):
        for i, line in enumerate(open(p, encoding="utf-8", errors="ignore"), 1):
            s = line.strip()
            if s.startswith("#"):
                continue
            if "trust_remote_code=True" in s or re.search(r"\bpickle\.load", s) or re.search(r"\bjoblib\.load", s):
                unsafe.append(f"{p}:{i}")
            if "torch.load(" in s and "weights_only=True" not in s:
                unsafe.append(f"{p}:{i}")
out("PASS" if not unsafe else "FAIL", "5  no trust_remote_code / pickle / unsafe torch.load" if not unsafe else "5  unsafe loading at: " + ", ".join(unsafe[:6]))

# 6. The blind acceptance set must never be referenced by training or tuning code.
leak = []
for p in FILES:
    if p.endswith(".py") and ("train" in os.path.basename(p) or "tune" in os.path.basename(p) or "distill" in os.path.basename(p)):
        t = open(p, encoding="utf-8", errors="ignore").read()
        if re.search(r"acceptance_set|acceptance[/\\]|acceptance\.(csv|json|jsonl|parquet)|ACCEPTANCE_(SET|PATH|FILE|DIR)", t):
            leak.append(p)
out("PASS" if not leak else "FAIL", "6  training/tuning code never references the acceptance set" if not leak else "6  acceptance referenced in: " + ", ".join(leak))

# 7. Every cycle log is valid and traceable.
cyc = sorted(glob.glob("docs/ml/cycles/cycle_*.json"))
if not cyc:
    out("PASS", "7  no cycle logs yet")
else:
    req = ("cycle", "hypothesis", "candidate_sha256", "dataset_manifest_sha256", "seeds", "dev_metrics", "per_language", "protected_fpr", "decision")
    miss = []
    for c in cyc:
        try:
            d = json.load(open(c, encoding="utf-8"))
            miss += [f"{os.path.basename(c)}:{k}" for k in req if k not in d]
        except Exception as ex:
            miss.append(f"{os.path.basename(c)}: unreadable")
    out("PASS" if not miss else "FAIL", f"7  {len(cyc)} cycle log(s) valid" if not miss else "7  cycle log problems: " + ", ".join(miss[:6]))

# 8. No promotional wording in ML docs.
words = re.compile(r"production-ready|10/10|perfect|state-of-the-art|human-level|flagship", re.I)
hits = 0
for p in glob.glob("docs/ml/**/*.md", recursive=True):
    for line in open(p, encoding="utf-8", errors="ignore"):
        low = line.lower()
        if words.search(line) and not re.search(r"\bnot\b|\*\*not\*\*|n't|\bnever\b|\bno\b", low):
            hits += 1
out("PASS" if hits == 0 else "WARN", "8  no promotional wording in docs/ml" if hits == 0 else f"8  {hits} line(s) of promotional wording in docs/ml")

# 10. Packaged candidates must be exactly the artifact that was measured (hash + size recorded in metadata.json).
cand_problems = []
for meta in glob.glob("ml/candidates/*/metadata.json"):
    d = os.path.dirname(meta)
    try:
        md = json.load(open(meta, encoding="utf-8"))
        mp = os.path.join(d, "model.json")
        if not os.path.exists(mp):
            cand_problems.append(f"{d}: model.json missing")
            continue
        if sha256(mp) != md.get("sha256"):
            cand_problems.append(f"{d}: model.json sha256 {sha256(mp)[:12]} != recorded {str(md.get('sha256'))[:12]}")
        if os.path.getsize(mp) != md.get("size_bytes"):
            cand_problems.append(f"{d}: size {os.path.getsize(mp)} != recorded {md.get('size_bytes')}")
        for c in glob.glob("docs/ml/cycles/cycle_*.json"):
            cj = json.load(open(c, encoding="utf-8"))
            if cj.get("decision") == "keep" and cj.get("candidate_sha256") == md.get("sha256") and sha256(mp) != cj["candidate_sha256"]:
                cand_problems.append(f"{os.path.basename(c)} candidate_sha256 matches no packaged file")
    except Exception as ex:
        cand_problems.append(f"{meta}: {ex}")
out("PASS" if not cand_problems else "FAIL", "10 packaged candidate hash/size match metadata and cycle logs" if not cand_problems else "10 " + "; ".join(sorted(set(cand_problems))[:4]))

# 11. Memory/heap claims in docs need a measurement record in a JSON file.
doc_claims = False
for p in glob.glob("docs/ml/**/*.md", recursive=True) + glob.glob("ml/**/*.md", recursive=True):
    for line in open(p, encoding="utf-8", errors="ignore"):
        if re.search(r"(heap|resident)", line, re.I) and re.search(r"\d\s*(MB|KB|MiB|KiB)", line, re.I) and not re.search(r"not measured", line, re.I):
            doc_claims = True
json_has = False
for p in glob.glob("ml/candidates/*/metadata.json"):
    try:
        if re.search(r"heap|resident", open(p, encoding="utf-8", errors="ignore").read(), re.I):
            json_has = True
    except Exception:
        pass
out("PASS" if (not doc_claims or json_has) else "FAIL", "11 memory claims are backed by a JSON measurement" if (not doc_claims or json_has) else "11 docs claim heap/resident memory values but no JSON file records a heap/resident measurement")

# 9. Working tree clean (this script excluded).
st = [l for l in subprocess.check_output(["git", "status", "--porcelain"], text=True).splitlines() if "verify_ml.py" not in l]
out("PASS" if not st else "FAIL", "9  working tree clean" if not st else "9  uncommitted changes")

print("-" * 60)
print(f"FAIL: {FAILS}   WARN: {WARNS}")
sys.exit(1 if FAILS else 0)
